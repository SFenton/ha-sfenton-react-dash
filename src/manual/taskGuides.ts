import type { ManualTaskGuideArticle } from './types'

export const MANUAL_TASK_GUIDE_MINIMUM_WORDS = 150

type ManualTaskGuideDefinition = Omit<ManualTaskGuideArticle, 'blocks' | 'kind' | 'tasks'>

function taskGuide(definition: ManualTaskGuideDefinition): ManualTaskGuideArticle {
  return {
    ...definition,
    blocks: [],
    kind: 'task-guide',
    tasks: [definition.taskGuide.canonicalQuestion],
  }
}

export function isManualTaskGuideArticle(article: { kind: string }): article is ManualTaskGuideArticle {
  return article.kind === 'task-guide'
}

export function manualTaskGuideAuthoredTextValues(article: ManualTaskGuideArticle) {
  const guide = article.taskGuide
  return [
    guide.canonicalQuestion,
    ...guide.prerequisites,
    ...guide.steps,
    ...guide.successConfirmation,
    guide.backCancelClosePath,
    ...guide.failureAndRecovery,
    ...guide.automaticBehaviorAndSideEffects,
    guide.safetyAndLimitations.title,
    guide.safetyAndLimitations.text,
    ...(guide.screenshotEvidence.nonvisualReason ? [guide.screenshotEvidence.nonvisualReason] : []),
    ...(guide.screenshotEvidence.missingDedicatedScreenshot ? [guide.screenshotEvidence.missingDedicatedScreenshot] : []),
  ]
}

export function manualTaskGuideWordCount(article: ManualTaskGuideArticle) {
  return manualTaskGuideAuthoredTextValues(article).join(' ').trim().split(/\s+/).filter(Boolean).length
}

