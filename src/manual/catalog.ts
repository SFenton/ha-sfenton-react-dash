function articleSection(id: string): ManualSectionId {
  if (START_ARTICLES.has(id)) return 'start'
  if (HOME_ARTICLES.has(id)) return 'home'
  if (SECURITY_ARTICLES.has(id)) return 'security'
  if (CLIMATE_ARTICLES.has(id)) return 'climate'
  if (CHORE_ARTICLES.has(id)) return 'chores'
  if (FOOD_ARTICLES.has(id)) return 'food'
  if (ROOM_ARTICLES_IDS.has(id) || id.startsWith('room-')) return 'rooms'
  if (SETTINGS_ARTICLES.has(id)) return 'settings'
  return 'help'
}

function articleKind(article: ManualArticleInput): ManualArticleKind {
  if (article.kind) return article.kind
  if (TECHNICAL_ARTICLES.has(article.id)) return 'technical-reference'
  if (PAGE_OVERVIEW_ARTICLES.has(article.id)) return 'page-overview'
  if (article.id.startsWith('room-')) return 'generated-room'
  return 'component-guide'
}

function finalizedArticle(article: ManualArticleInput): ManualArticle {
  const configuredSurfaceGuide = article.surfaceGuide ?? MANUAL_SURFACE_GUIDE_PAYLOADS_BY_ARTICLE_ID[article.id]
  const kind = configuredSurfaceGuide ? 'surface-guide' : articleKind(article)
  const sectionId = articleSection(article.id)
  const { pageGuide, relatedArticleIds, surfaceGuide, ...base } = article
  if (kind === 'surface-guide') {
    if (!configuredSurfaceGuide) throw new Error(`Surface guide ${article.id} has no structured surfaceGuide payload.`)
    if (pageGuide) throw new Error(`Surface guide ${article.id} cannot also contain pageGuide content.`)
    return {
      ...base,
      kind,
      sectionId,
      blocks: [],
      surfaceGuide: configuredSurfaceGuide,
    }
  }
  if (kind === 'page-guide') {
    if (!pageGuide) throw new Error(`Page guide ${article.id} has no structured pageGuide payload.`)
    if (base.blocks.length !== 0) throw new Error(`Page guide ${article.id} must keep all authored content in pageGuide.`)
    if (relatedArticleIds) throw new Error(`Page guide ${article.id} must keep related links in pageGuide.`)
    return {
      ...base,
      kind,
      sectionId,
      blocks: [],
      pageGuide,
    }
  }
  if (kind === 'family-guide') throw new Error(`Family guide ${article.id} must be defined with its structured familyGuide payload.`)
  if (pageGuide || surfaceGuide) throw new Error(`Manual article ${article.id} has structured guide content without the matching article kind.`)
  return {
    ...base,
    kind: kind as ManualStandardArticleKind,
    ...(relatedArticleIds ? { relatedArticleIds } : {}),
    sectionId,
  }
}

function attachCanonicalSurfaceOwnership(article: ManualArticle): ManualArticle {
  const ownsSurfaceIds = [...new Set([
    ...(article.ownsSurfaceIds ?? []),
    ...canonicalSurfaceIdsOwnedByArticle(article.id),
  ])]
  return ownsSurfaceIds.length > 0 ? { ...article, ownsSurfaceIds } : article
}

function attachRouteContextScreenshot(article: ManualArticle): ManualArticle {
  if (article.kind !== 'page-guide') return article
  const routeContextId = routeContextScreenshotIdForPath(article.pageGuide.routePath)
  if (!routeContextId || article.pageGuide.screenshotIds.includes(routeContextId)) return article
  return {
    ...article,
    pageGuide: {
      ...article.pageGuide,
      screenshotIds: [routeContextId, ...article.pageGuide.screenshotIds] as ManualPageGuide['screenshotIds'],
    },
  }
}

